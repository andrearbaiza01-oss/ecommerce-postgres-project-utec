-- ===========================================================================
-- 02 - CORE: modelo dimensional (estrella) + reglas de negocio del Excel
-- Las columnas calculadas se definen como GENERATED ALWAYS ... STORED para
-- que la base replique EXACTAMENTE las formulas de la hoja de calculo:
--   SUBTOTAL        = cantidad * precio_unitario          (=PRODUCT(I,J))
--   IGV (18%)       = subtotal * 0.18                     (=L*$M$2)
--   UTILIDAD        = subtotal * 0.25                     (=L*$N$2)
--   COSTO UNITARIO  = precio_unitario * 0.60              (=J*$O$2)
--   COSTO TOTAL     = costo_unitario * cantidad           (=PRODUCT(O,I))
--   TOTAL DE VENTA  = subtotal + igv                      (=SUM(L,M))
--   VENTA TOTAL ($) = total_venta / 3.75                  (=Q/$P$2)
--   GANANCIA        = subtotal - costo_total              (=L-P)
--   ESTADO          = IF(ganancia>0,'Ganancia','Perdida')
-- Postgres no permite que una columna generada referencie otra generada, por
-- eso cada expresion se escribe en funcion de las columnas base.
-- ===========================================================================
SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------------
-- Parametros de negocio versionados (reemplazan las celdas fijas del Excel)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core.parametro_negocio (
    clave          text        NOT NULL,
    valor          numeric(18,6) NOT NULL,
    unidad         text,
    descripcion    text,
    vigente_desde  date        NOT NULL DEFAULT DATE '2025-01-01',
    vigente_hasta  date,
    PRIMARY KEY (clave, vigente_desde)
);

INSERT INTO core.parametro_negocio (clave, valor, unidad, descripcion) VALUES
    ('IGV',               0.18, 'ratio',  'Impuesto General a las Ventas aplicado al subtotal'),
    ('MARGEN_UTILIDAD',   0.25, 'ratio',  'Margen de utilidad teorico sobre el subtotal'),
    ('FACTOR_COSTO',      0.60, 'ratio',  'Costo unitario como fraccion del precio de venta'),
    ('TIPO_CAMBIO_USD',   3.75, 'PEN/USD','Tipo de cambio Soles -> Dolares')
ON CONFLICT (clave, vigente_desde) DO UPDATE
   SET valor = EXCLUDED.valor, descripcion = EXCLUDED.descripcion;

-- ---------------------------------------------------------------------------
-- DIMENSIONES
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS core.fact_venta CASCADE;
DROP TABLE IF EXISTS core.dim_cliente CASCADE;
DROP TABLE IF EXISTS core.dim_producto CASCADE;
DROP TABLE IF EXISTS core.dim_sucursal CASCADE;
DROP TABLE IF EXISTS core.dim_vendedor CASCADE;
DROP TABLE IF EXISTS core.dim_metodo_pago CASCADE;

CREATE TABLE core.dim_sucursal (
    sucursal_sk    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal_nk    text NOT NULL UNIQUE,
    nombre         text NOT NULL,
    departamento   text,
    macro_region   text,
    activa         boolean NOT NULL DEFAULT true,
    ingestion_ts   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.dim_sucursal IS 'Sucursales de atencion (Puno, Arequipa, Juliaca).';

CREATE TABLE core.dim_vendedor (
    vendedor_sk    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendedor_nk    text NOT NULL UNIQUE,
    nombre         text NOT NULL,
    sucursal_sk    integer REFERENCES core.dim_sucursal(sucursal_sk),
    ingestion_ts   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.dim_vendedor IS 'Vendedor responsable de la operacion.';

CREATE TABLE core.dim_metodo_pago (
    metodo_pago_sk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metodo_pago_nk text NOT NULL UNIQUE,
    nombre         text NOT NULL,
    instrumento    text NOT NULL,   -- digital | bancario | efectivo | tarjeta
    es_digital     boolean NOT NULL DEFAULT false,
    ingestion_ts   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.dim_metodo_pago IS 'Metodo de pago (Yape, Transferencia, Deposito, Tarjeta, Efectivo).';

CREATE TABLE core.dim_producto (
    producto_sk        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_nk        text NOT NULL UNIQUE,
    nombre_producto    text NOT NULL,
    categoria          text NOT NULL,
    precio_lista_pen   numeric(18,4) NOT NULL CHECK (precio_lista_pen > 0),
    costo_unitario_pen numeric(18,4) GENERATED ALWAYS AS (precio_lista_pen * 0.60) STORED,
    ingestion_ts       timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.dim_producto IS 'Catalogo de productos con precio de lista y costo derivado (factor 0.60).';

CREATE TABLE core.dim_cliente (
    cliente_sk      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nk      text NOT NULL UNIQUE,
    nombre_cliente  text NOT NULL,
    tipo_cliente    text NOT NULL CHECK (tipo_cliente IN ('Empresa','Persona natural')),
    pais            text NOT NULL DEFAULT 'Peru',
    ciudad          text,
    segmento        text,
    origen_registro text NOT NULL DEFAULT 'EXCEL' CHECK (origen_registro IN ('EXCEL','STREAM_SINTETICO')),
    es_cliente_real boolean NOT NULL DEFAULT true,
    fecha_alta      date,
    ingestion_ts    timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.dim_cliente IS 'Dimension conformada de clientes. es_cliente_real=false marca clientes generados para el event stream.';
COMMENT ON COLUMN core.dim_cliente.origen_registro IS 'EXCEL = uno de los 30 clientes reales; STREAM_SINTETICO = cliente generado para la simulacion del stream.';

-- ---------------------------------------------------------------------------
-- DIMENSION FECHA (calendario completo, usado por el event stream)
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS core.dim_fecha CASCADE;
CREATE TABLE core.dim_fecha (
    fecha_sk        integer PRIMARY KEY,          -- yyyymmdd
    fecha           date    NOT NULL UNIQUE,
    anio            smallint NOT NULL,
    trimestre       smallint NOT NULL,
    mes            smallint NOT NULL,
    nombre_mes      text    NOT NULL,
    semana_iso      smallint NOT NULL,
    dia             smallint NOT NULL,
    dia_semana      smallint NOT NULL,
    nombre_dia      text    NOT NULL,
    es_fin_semana   boolean NOT NULL,
    anio_mes        text    NOT NULL,
    primer_dia_mes  date    NOT NULL,
    ultimo_dia_mes  date    NOT NULL
);

INSERT INTO core.dim_fecha
SELECT  (to_char(d,'YYYYMMDD'))::int                            AS fecha_sk,
        d::date                                                  AS fecha,
        EXTRACT(YEAR    FROM d)::smallint                         AS anio,
        EXTRACT(QUARTER FROM d)::smallint                         AS trimestre,
        EXTRACT(MONTH   FROM d)::smallint                         AS mes,
        CASE EXTRACT(MONTH FROM d)::int
            WHEN 1 THEN 'Enero'   WHEN 2 THEN 'Febrero' WHEN 3 THEN 'Marzo'
            WHEN 4 THEN 'Abril'   WHEN 5 THEN 'Mayo'    WHEN 6 THEN 'Junio'
            WHEN 7 THEN 'Julio'   WHEN 8 THEN 'Agosto'  WHEN 9 THEN 'Setiembre'
            WHEN 10 THEN 'Octubre' WHEN 11 THEN 'Noviembre' ELSE 'Diciembre' END,
        EXTRACT(WEEK FROM d)::smallint,
        EXTRACT(DAY  FROM d)::smallint,
        EXTRACT(ISODOW FROM d)::smallint,
        CASE EXTRACT(ISODOW FROM d)::int
            WHEN 1 THEN 'Lunes' WHEN 2 THEN 'Martes' WHEN 3 THEN 'Miercoles'
            WHEN 4 THEN 'Jueves' WHEN 5 THEN 'Viernes' WHEN 6 THEN 'Sabado'
            ELSE 'Domingo' END,
        EXTRACT(ISODOW FROM d)::int >= 6,
        to_char(d,'YYYY-MM'),
        date_trunc('month', d)::date,
        (date_trunc('month', d) + INTERVAL '1 month - 1 day')::date
FROM generate_series(DATE '2024-01-01', DATE '2027-12-31', INTERVAL '1 day') AS g(d)
ON CONFLICT (fecha_sk) DO NOTHING;

-- ---------------------------------------------------------------------------
-- HECHO: ventas del Excel (grano = 1 operacion registrada = 1 fila del Excel)
-- ---------------------------------------------------------------------------
CREATE TABLE core.fact_venta (
    venta_sk            bigserial PRIMARY KEY,
    fila_excel          integer NOT NULL UNIQUE,
    cliente_sk          integer NOT NULL REFERENCES core.dim_cliente(cliente_sk),
    producto_sk         integer NOT NULL REFERENCES core.dim_producto(producto_sk),
    sucursal_sk         integer NOT NULL REFERENCES core.dim_sucursal(sucursal_sk),
    vendedor_sk         integer NOT NULL REFERENCES core.dim_vendedor(vendedor_sk),
    metodo_pago_sk      integer NOT NULL REFERENCES core.dim_metodo_pago(metodo_pago_sk),

    -- medidas base
    cantidad            numeric(18,4) NOT NULL CHECK (cantidad >= 0),
    precio_unitario_pen numeric(18,4) NOT NULL CHECK (precio_unitario_pen > 0),

    -- medidas derivadas (replican las formulas del Excel)
    subtotal_pen        numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen) STORED,
    igv_pen             numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 0.18) STORED,
    utilidad_pen        numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 0.25) STORED,
    costo_unitario_pen  numeric(18,4) GENERATED ALWAYS AS (precio_unitario_pen * 0.60) STORED,
    costo_total_pen     numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 0.60) STORED,
    total_venta_pen     numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 1.18) STORED,
    total_venta_usd     numeric(18,6) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 1.18 / 3.75) STORED,
    ganancia_pen        numeric(18,4) GENERATED ALWAYS AS (cantidad * precio_unitario_pen * 0.40) STORED,
    estado              text          GENERATED ALWAYS AS
        (CASE WHEN cantidad * precio_unitario_pen * 0.40 > 0 THEN 'Ganancia' ELSE 'Perdida' END) STORED,
    es_conversion       boolean       GENERATED ALWAYS AS (cantidad > 0) STORED,

    hash_fila           char(64) NOT NULL,
    ingestion_ts        timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE core.fact_venta IS 'Hecho transaccional de ventas (30 filas del Excel). Medidas derivadas garantizadas por columnas generadas.';
COMMENT ON COLUMN core.fact_venta.es_conversion IS 'FALSE cuando cantidad=0: operacion registrada sin conversion (ESTADO=Perdida en el Excel).';

CREATE INDEX IF NOT EXISTS ix_fact_venta_cliente  ON core.fact_venta (cliente_sk);
CREATE INDEX IF NOT EXISTS ix_fact_venta_producto ON core.fact_venta (producto_sk);
CREATE INDEX IF NOT EXISTS ix_fact_venta_sucursal ON core.fact_venta (sucursal_sk);
CREATE INDEX IF NOT EXISTS ix_fact_venta_estado   ON core.fact_venta (estado);
