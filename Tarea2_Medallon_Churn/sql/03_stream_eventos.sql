-- ===========================================================================
-- 03 - STREAM: event stream de e-commerce (append-only, particionado por mes)
--
-- IMPORTANTE / TRAZABILIDAD:
-- El Excel origen NO contiene marcas de tiempo ni historial por cliente
-- (30 filas, 1 operacion por cliente, sin fechas). Para habilitar la
-- arquitectura medallon con ingesta incremental y el modelo de churn, este
-- esquema contiene un event stream DERIVADO: los catalogos (productos,
-- categorias, sucursales, vendedores, metodos de pago, ciudades, mix de
-- tipo de cliente) y los precios provienen 100% del Excel real; las marcas
-- de tiempo, sesiones y los clientes adicionales son SIMULADOS de forma
-- reproducible (semilla fija). Los 30 clientes reales quedan marcados con
-- core.dim_cliente.es_cliente_real = true.
-- ===========================================================================
SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS stream.evento CASCADE;

CREATE TABLE stream.evento (
    event_id            bigint GENERATED BY DEFAULT AS IDENTITY,
    event_uuid          uuid        NOT NULL DEFAULT gen_random_uuid(),
    event_ts            timestamptz NOT NULL,
    event_date          date        NOT NULL,
    event_type          text        NOT NULL CHECK (event_type IN (
                            'session_start','product_view','search','add_to_cart',
                            'remove_from_cart','checkout_start','order_placed',
                            'order_cancelled','payment_failed','return_requested',
                            'support_ticket','review_submitted','newsletter_unsubscribe')),
    cliente_sk          integer     NOT NULL REFERENCES core.dim_cliente(cliente_sk),
    session_id          uuid        NOT NULL,
    canal               text        NOT NULL CHECK (canal IN ('web','app_movil','marketplace','whatsapp','tienda')),
    dispositivo         text        CHECK (dispositivo IN ('desktop','mobile','tablet','pos')),
    producto_sk         integer     REFERENCES core.dim_producto(producto_sk),
    categoria           text,
    cantidad            numeric(18,4),
    precio_unitario_pen numeric(18,4),
    monto_pen           numeric(18,4),
    metodo_pago_sk      integer     REFERENCES core.dim_metodo_pago(metodo_pago_sk),
    sucursal_sk         integer     REFERENCES core.dim_sucursal(sucursal_sk),
    vendedor_sk         integer     REFERENCES core.dim_vendedor(vendedor_sk),
    order_id            uuid,
    campania            text,
    utm_source          text,
    descuento_pct       numeric(6,4) DEFAULT 0,
    tiempo_sesion_seg   integer,
    source_system       text        NOT NULL DEFAULT 'ecommerce_web',
    es_sintetico        boolean     NOT NULL DEFAULT true,
    ingestion_ts        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id, event_ts)
) PARTITION BY RANGE (event_ts);

COMMENT ON TABLE stream.evento IS 'Event stream de e-commerce, append-only, particionado mensualmente por event_ts. Catalogos reales (Excel) + temporalidad simulada reproducible.';
COMMENT ON COLUMN stream.evento.es_sintetico IS 'TRUE: la marca de tiempo/sesion fue generada por el simulador reproducible (ver scripts/20_generar_event_stream.py).';

-- Particiones mensuales 2025-01 .. 2027-12 + particion por defecto
DO $$
DECLARE
    d date := DATE '2025-01-01';
    fin date := DATE '2028-01-01';
    nombre text;
BEGIN
    WHILE d < fin LOOP
        nombre := format('evento_p%s', to_char(d, 'YYYYMM'));
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS stream.%I PARTITION OF stream.evento FOR VALUES FROM (%L) TO (%L)',
            nombre, d, (d + INTERVAL '1 month')::date);
        d := (d + INTERVAL '1 month')::date;
    END LOOP;
    EXECUTE 'CREATE TABLE IF NOT EXISTS stream.evento_pdefault PARTITION OF stream.evento DEFAULT';
END $$;

CREATE INDEX IF NOT EXISTS ix_evento_ts        ON stream.evento (event_ts);
CREATE INDEX IF NOT EXISTS ix_evento_cliente   ON stream.evento (cliente_sk, event_ts DESC);
CREATE INDEX IF NOT EXISTS ix_evento_tipo      ON stream.evento (event_type, event_ts);
CREATE INDEX IF NOT EXISTS ix_evento_order     ON stream.evento (order_id) WHERE order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_evento_ingestion ON stream.evento (ingestion_ts);

-- ---------------------------------------------------------------------------
-- Vista de ordenes efectivas (lo que un sistema OLTP expondria como pedidos)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW stream.v_orden AS
SELECT  e.order_id,
        e.cliente_sk,
        e.event_ts                                   AS fecha_orden,
        e.event_date,
        e.producto_sk,
        e.categoria,
        e.cantidad,
        e.precio_unitario_pen,
        e.monto_pen,
        ROUND(e.monto_pen * 0.18, 4)                 AS igv_pen,
        ROUND(e.monto_pen * 1.18, 4)                 AS total_con_igv_pen,
        ROUND(e.monto_pen * 1.18 / 3.75, 6)          AS total_usd,
        ROUND(e.monto_pen * 0.40, 4)                 AS ganancia_pen,
        e.metodo_pago_sk,
        e.sucursal_sk,
        e.vendedor_sk,
        e.canal,
        e.campania,
        EXISTS (SELECT 1 FROM stream.evento c
                 WHERE c.order_id = e.order_id AND c.event_type = 'order_cancelled') AS fue_cancelada,
        EXISTS (SELECT 1 FROM stream.evento r
                 WHERE r.order_id = e.order_id AND r.event_type = 'return_requested') AS tuvo_devolucion
FROM    stream.evento e
WHERE   e.event_type = 'order_placed';

COMMENT ON VIEW stream.v_orden IS 'Ordenes colocadas derivadas del event stream, con flags de cancelacion y devolucion.';

-- ---------------------------------------------------------------------------
-- Funcion de ingesta incremental para Bronze: entrega eventos nuevos y
-- actualiza el watermark (patron pull con marca de agua)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION stream.fn_eventos_incrementales(
    p_desde_ts timestamptz DEFAULT NULL,
    p_limite   integer     DEFAULT 1000000)
RETURNS SETOF stream.evento
LANGUAGE sql STABLE AS $$
    SELECT *
    FROM   stream.evento
    WHERE  ingestion_ts > COALESCE(p_desde_ts, '-infinity'::timestamptz)
    ORDER  BY ingestion_ts, event_id
    LIMIT  p_limite;
$$;
COMMENT ON FUNCTION stream.fn_eventos_incrementales IS 'Entrega los eventos con ingestion_ts posterior al watermark recibido (ingesta incremental a Bronze).';
